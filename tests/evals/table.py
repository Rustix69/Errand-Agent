"""Rendering of artifacts/eval_table.md from the scenario records of a test run. Pure functions, unit-tested in
test_eval_table.py. The table is generated, never edited by hand.

Columns: Scenario | Expected | Actual | Pass/Fail | Notes.  `Actual` is recorded from DB state and trace events by
the scenario itself, `Pass/Fail` comes from the pytest outcome of that scenario's test.
"""

from __future__ import annotations

import ast
import re
from pathlib import Path
from typing import Any

COLUMNS = ("Scenario", "Expected", "Actual", "Pass/Fail", "Notes")
GROUPS = "BESFLCMRP"  # basic, examples, safety, failures, limits, context, memory, restart, proactive

# CLAUDE.md §3 (Evaluation) and §6 (each example request has an eval) -> the scenarios that cover it.
# This index is declared by hand; the generator checks every id against the run, and a test checks it against the
# source, so a renamed or missing scenario shows up as MISSING instead of silently passing.
REQUIRED_CASES: dict[str, tuple[str, ...]] = {
    "The three example requests": ("E1", "E2", "E3"),
    "Adversarial input": ("S1", "S2", "S3"),
    "Prompt injection": ("S4", "S5"),
    "Changed price / slot after approval": ("S6", "S7"),
    "Booking timeout after possible success": ("F1", "F2", "F3"),
    "Slot conflict": ("F6",),
    "Repeated confirmation": ("S8", "R4"),
    "Memory correction and forgetting": ("M1", "M2"),
    "Restart mid-booking (crash injection)": ("R1", "R2", "R3"),
    "Proactive cancellation": ("P1", "P2", "P3", "P4", "P5"),
    "Context budget": ("C1", "C2", "C3"),
    "Limit exhaustion": ("L1", "L2", "L3"),
    "Tool failures": ("F4", "F5", "F7", "F8"),
}


def order_key(sid: str) -> tuple[int, int]:
    m = re.fullmatch(r"([A-Z])(\d+)", sid)
    return (GROUPS.index(m[1]), int(m[2])) if m and m[1] in GROUPS else (len(GROUPS), 0)


def _esc(s: str) -> str:
    return " ".join(str(s).replace("|", "\\|").split())


def verdict(outcome: str) -> str:
    return {"pass": "pass", "FAIL": "FAIL"}.get(outcome, "not run")


def render_table(records: list[Any], required: dict[str, tuple[str, ...]] = REQUIRED_CASES) -> str:
    """`records` need .id .scenario .expected .actual .notes .outcome ('pass' | 'FAIL' | anything else = not run)."""
    recs = sorted(records, key=lambda r: order_key(r.id))
    passed = sum(r.outcome == "pass" for r in recs)
    failed = sum(r.outcome == "FAIL" for r in recs)
    lines = [
        "# Eval table", "",
        "Generated by the test run (`pytest`, `tests/evals`); do not edit by hand. "
        f"{len(recs)} scenarios: {passed} pass, {failed} FAIL, {len(recs) - passed - failed} not run. "
        "Assertions are on DB state and trace events, never on reply wording. The table is written only by a run "
        "that covers every eval file.", "",
        "| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS),
    ]
    for r in recs:
        lines.append(f"| {_esc(f'{r.id} · {r.scenario}')} | {_esc(r.expected)} | {_esc(r.actual)} | "
                     f"{verdict(r.outcome)} | {_esc(r.notes)} |")
    by_id = {r.id: r for r in recs}
    lines += ["", "## Required cases (CLAUDE.md §3)", "",
              "Which scenarios cover each required case. The index is declared in `tests/evals/table.py` and checked "
              "against the run: an id that did not run shows as MISSING.", "",
              "| Case | Scenarios | Pass/Fail |", "|---|---|---|"]
    for case, ids in required.items():
        missing = [i for i in ids if i not in by_id]
        if missing:
            result = "MISSING " + ", ".join(missing)
        else:
            result = "pass" if all(by_id[i].outcome == "pass" for i in ids) else "FAIL"
        lines.append(f"| {_esc(case)} | {', '.join(ids)} | {result} |")
    return "\n".join(lines) + "\n"


def eval_test_names(path: Path) -> set[str]:
    return {n.name for n in ast.parse(path.read_text()).body if isinstance(n, ast.FunctionDef) and n.name.startswith("test_")}


def is_full_run(evals_dir: Path, collected: dict[str, set[str]]) -> bool:
    """True when the run collected every test function of every eval file (no file or -k selection left any out)."""
    files = sorted(evals_dir.glob("test_*.py"))
    return bool(files) and all(eval_test_names(f) <= collected.get(f.name, set()) for f in files)
