"""Eval recorder. Each scenario declares `expected` and records `actual` (from DB state / trace events) through
the `eval_case` / `scenario` fixtures; a hook writes artifacts/eval_table.md after every run that included
evals: scenario, expected, actual, pass/fail, notes. Wording of replies is never asserted."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

import pytest

from tests.agent.conftest import make_agent  # noqa: F401  (shared fixture)
from tests.evals.harness import Run, Turn

ARTIFACTS = Path(__file__).resolve().parents[2] / "artifacts"
GROUPS = "BESFLCMR"  # table order: basic, examples, safety, failures, limits, context, memory, restart
_RECORDS: list["EvalRecord"] = []


@dataclass
class EvalRecord:
    scenario: str
    expected: str
    actual: str = ""
    notes: str = ""
    outcome: str = "not run"
    id: str = ""
    extra: dict = field(default_factory=dict)

    def order(self) -> tuple[int, int]:
        m = re.fullmatch(r"([A-Z])(\d+)", self.id)
        return (GROUPS.index(m[1]), int(m[2])) if m else (len(GROUPS), 0)


@pytest.fixture
def eval_case(request):
    def _declare(scenario: str, expected: str, notes: str = "", id: str = "") -> EvalRecord:
        rec = EvalRecord(scenario, expected, notes=notes, id=id)
        request.node._eval_record = rec
        _RECORDS.append(rec)
        return rec

    return _declare


@pytest.fixture
def scenario(make_agent, eval_case):
    """scenario(id, name, expected, script, user=[...], notes=..., env_kw=..., seed=..., ...) -> Run"""

    def _go(sid: str, name: str, expected: str, script, user: list[str | Turn] = (), *, notes: str = "",
            env_kw: dict | None = None, **agent_kw) -> Run:
        rec = eval_case(name, expected, notes, id=sid)
        run = Run(make_agent, make_agent(script, env_kw=env_kw, **agent_kw), rec)
        run.record()
        run.play(list(user))
        return run

    return _go


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    rec = getattr(item, "_eval_record", None)
    if rec is not None and rep.when == "call":
        rec.outcome = "pass" if rep.passed else "FAIL"


def pytest_sessionfinish(session, exitstatus):
    if not _RECORDS:
        return
    ARTIFACTS.mkdir(exist_ok=True)
    recs = sorted(_RECORDS, key=lambda r: r.order())
    esc = lambda s: s.replace("|", "\\|").replace("\n", " ")  # noqa: E731
    passed = sum(r.outcome == "pass" for r in recs)
    rows = ["| ID | Scenario | Expected | Actual | Result | Notes |", "|---|---|---|---|---|---|"]
    rows += [f"| {r.id} | {esc(r.scenario)} | {esc(r.expected)} | {esc(r.actual)} | {r.outcome} | {esc(r.notes)} |"
             for r in recs]
    (ARTIFACTS / "eval_table.md").write_text(
        "# Eval table\n\nGenerated by the test run (`tests/evals`). Do not edit by hand. "
        f"{len(recs)} scenarios, {passed} pass, {len(recs) - passed} not passing. Assertions are on DB state and "
        "trace events, never on reply wording.\n\n" + "\n".join(rows) + "\n"
    )
