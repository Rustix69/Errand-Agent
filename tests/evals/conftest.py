"""Minimal eval recorder (Step 9 polishes it). Each scenario declares `expected`, records `actual` from
DB state / trace events, and a hook writes artifacts/eval_table.md after the run. Wording is never asserted."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import pytest

from tests.agent.conftest import make_agent  # noqa: F401  (shared fixture)

ARTIFACTS = Path(__file__).resolve().parents[2] / "artifacts"
_RECORDS: list["EvalRecord"] = []


@dataclass
class EvalRecord:
    scenario: str
    expected: str
    actual: str = ""
    notes: str = ""
    outcome: str = "not run"
    extra: dict = field(default_factory=dict)


@pytest.fixture
def eval_case(request):
    def _declare(scenario: str, expected: str, notes: str = "") -> EvalRecord:
        rec = EvalRecord(scenario, expected, notes=notes)
        request.node._eval_record = rec
        _RECORDS.append(rec)
        return rec

    return _declare


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    rec = getattr(item, "_eval_record", None)
    if rec is not None and rep.when == "call":
        rec.outcome = "pass" if rep.passed else "FAIL"


def pytest_sessionfinish(session, exitstatus):
    if not _RECORDS:
        return
    ARTIFACTS.mkdir(exist_ok=True)
    rows = ["| Scenario | Expected | Actual | Result | Notes |", "|---|---|---|---|---|"]
    for r in _RECORDS:
        esc = lambda s: s.replace("|", "\\|").replace("\n", " ")
        rows.append(f"| {esc(r.scenario)} | {esc(r.expected)} | {esc(r.actual)} | {r.outcome} | {esc(r.notes)} |")
    (ARTIFACTS / "eval_table.md").write_text(
        "# Eval table\n\nGenerated by the test run (tests/evals). Do not edit by hand.\n\n" + "\n".join(rows) + "\n"
    )
